```' "$MEDIA_MAP_FIX"
TESTS_RUN=$((TESTS_RUN + 1))
fenced_media_count=$(printf '%s' "$MEDIA_OUT" | jq -c '[.content[] | select(.type=="mediaSingle")] | length')
