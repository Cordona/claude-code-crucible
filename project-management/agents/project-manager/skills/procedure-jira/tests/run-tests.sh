#!/usr/bin/env sh
#
# run-tests.sh — self-contained, zero-dependency POSIX test harness for
#                md-to-adf.sh: the markdown->ADF converter.
#
# WHY a hand-rolled harness (not bats): same rationale as
# procedure-gh-issues/tests/run-tests.sh — the whole point of this suite is
# "runs on any machine with no dependencies beyond jq". Requiring bats-core
# would contradict that.
#
# What it does:
#   * Golden-file comparison: for each fixture in fixtures/*.md, runs
#     md-to-adf.sh and diffs its CANONICALIZED (`jq -S`) output against the
#     matching fixtures/*.expected.json (also canonicalized before compare,
#     so key order never causes a false failure).
#
#     MOST *.expected.json files were generated by driving the jira.py
#     reference oracle directly — a future regenerator must ALWAYS drive the
#     oracle, never md-to-adf.sh itself (that would make the corpus circular
#     and unable to catch a regression). The exact command, run from
#     vendor-jira/.claude/skills/jira/scripts (so `import jira` resolves):
#       python3 -c "import json,jira,pathlib as p; \
#         t=p.Path('NAME.md').read_text(); \
#         print(json.dumps(jira.create_adf_document(jira.markdown_to_adf_content(t))))" \
#         > NAME.expected.json
#
#     The following are HAND-WRITTEN instead, because they assert a
#     deliberate, documented DIVERGENCE from the oracle (see md-to-adf.sh's
#     header) rather than
#     oracle parity: rule (--- -> rule, not a literal paragraph),
#     line-drop-regression (the oracle's line-drop bug, deliberately NOT
#     reproduced), degenerate-inline and link-scheme-reject (its
#     scheme allow-list has no oracle equivalent), empty-input and
#     whitespace-only (the empty-paragraph fallback has no oracle
#     equivalent — the oracle returns content:[]), and italic-underscore /
#     italic-star / mixed-bold-italic-code / adjacent-bold-italic /
#     unclosed-degrade (the oracle has NO italic support at all — `em` is
#     an extension with no oracle output to generate against, so these five
#     are hand-authored the same way).
#
#     The FULL-ADF-set fixtures are hand-authored for the SAME reason —
#     the oracle predates all of them, full stop: strike, headings-1-6,
#     bold-italic-stacked, hardbreak, code-block-plain/-lang/-markdown-
#     inside, blockquote-plain, panel-info/-note/-warning/-success/-error/
#     -alias-tip, nested-list, table-basic, table-empty-cell. (table-basic
#     replaces the old degrade-table fixture from before real table support
#     existed — the SAME input now correctly parses as a table instead of
#     degrading, which is the feature working, not a regression; the
#     "unrecognized construct still degrades to a paragraph" behavior it
#     used to cover is now exercised by degrade-unsupported instead, which
#     — unlike table-basic — genuinely IS oracle-parity-generated, since a
#     footnote reference isn't special to the oracle either.)
#   * Runs the converter under an isolated PATH toolbox that OMITS jq for
#     the "jq absent" test, and a separate toolbox that swaps in a
#     Oniguruma-less jq STUB for the "Oniguruma missing" test — both without
#     ever touching the real system jq.
#   * Exercises usage/argument errors and their exit codes.
#
# Usage:  sh run-tests.sh              # run all tests
#         VERBOSE=1 sh run-tests.sh
#         (also runs green under dash: dash run-tests.sh)
#
# Exit 0 = all passed, 1 = one or more failed.
#
set -eu

# ---------------------------------------------------------------------------
# Locations
# ---------------------------------------------------------------------------
TESTS_DIR=$(cd "$(dirname "$0")" && pwd)
SCRIPTS_DIR=$(cd "$TESTS_DIR/../skill/scripts" && pwd)
FIXTURES_DIR="$TESTS_DIR/fixtures"
CONVERTER="$SCRIPTS_DIR/md-to-adf.sh"

WORK=$(mktemp -d "${TMPDIR:-/tmp}/md-to-adf-tests.XXXXXX")
TOOLBOX="$WORK/toolbox"       # real tools, INCLUDING the real jq
NOJQ_TOOLBOX="$WORK/nojq"     # real tools, jq deliberately OMITTED
STUBJQ_DIR="$WORK/stubjq"     # ONLY a stub `jq` with no Oniguruma support
mkdir -p "$TOOLBOX" "$NOJQ_TOOLBOX" "$STUBJQ_DIR" "$WORK/home"

# shellcheck disable=SC2329  # invoked indirectly via trap
cleanup() { rm -rf "$WORK"; }
trap cleanup EXIT INT TERM

# ---------------------------------------------------------------------------
# Isolated PATH toolboxes: symlink only the real tools md-to-adf.sh needs.
# ---------------------------------------------------------------------------
ORIG_PATH=$PATH
link_tool() {
	target_dir=$1
	tool_name=$2
	tool_path=$(PATH="$ORIG_PATH" command -v "$tool_name" 2>/dev/null || true)
	[ -n "$tool_path" ] || { printf 'FATAL: required tool not found: %s\n' "$tool_name" >&2; exit 1; }
	ln -s "$tool_path" "$target_dir/$tool_name"
}
for t in sh mktemp grep sed cat rm cut mv tr; do
	link_tool "$TOOLBOX" "$t"
	link_tool "$NOJQ_TOOLBOX" "$t"
done
link_tool "$TOOLBOX" jq

# A stub named exactly `jq`, alone in its own directory, with NO
# regex/Oniguruma support at all: exercises the Oniguruma-assertion path
# deterministically, without depending on any real jq build's compile-time
# flags. Any call to `test(...)` fails, matching what a jq built without
# Oniguruma actually does. Prepending $STUBJQ_DIR to $NOJQ_TOOLBOX on PATH
# gives the script a `jq` that resolves to this stub, plus every other real
# tool it needs.
cat >"$STUBJQ_DIR/jq" <<'JQ_STUB'
#!/usr/bin/env sh
printf 'jq: error: test/0 is not defined (Oniguruma support not compiled in)\n' >&2
exit 5
JQ_STUB
chmod +x "$STUBJQ_DIR/jq"

# ---------------------------------------------------------------------------
# Runner primitives (same shape as procedure-gh-issues/tests/run-tests.sh)
# ---------------------------------------------------------------------------
TESTS_RUN=0
TESTS_FAIL=0
CUR_OUT=""
CUR_ERR=""
CUR_RC=0

# run <toolbox_dir> [VAR=VALUE ...] <cmd> [args...]
run() {
	r_path=$1; shift
	set +e
	env -i \
		HOME="$WORK/home" \
		PATH="$r_path" \
		TMPDIR="$WORK" \
		"$@" >"$WORK/out" 2>"$WORK/err"
	CUR_RC=$?
	set -e
	CUR_OUT=$(cat "$WORK/out"); CUR_ERR=$(cat "$WORK/err")
	rm -f "$WORK/out" "$WORK/err"
	if [ "${VERBOSE:-0}" = "1" ]; then
		printf '    rc=%s\n' "$CUR_RC"
		printf '%s\n' "$CUR_OUT" | sed 's/^/    out| /'
		printf '%s\n' "$CUR_ERR" | sed 's/^/    err| /'
	fi
}

pass() { printf '  ok   %s\n' "$1"; }
fail() { printf '  FAIL %s\n' "$1"; [ -n "${2:-}" ] && printf '       %s\n' "$2"; TESTS_FAIL=$((TESTS_FAIL + 1)); }

check() { TESTS_RUN=$((TESTS_RUN + 1)); if [ "$3" -eq 0 ]; then pass "$1"; else fail "$1" "$2"; fi; }

expect_rc() {
	TESTS_RUN=$((TESTS_RUN + 1))
	if [ "$CUR_RC" -eq "$2" ]; then pass "$1"
	else fail "$1" "expected exit $2, got $CUR_RC; stderr: $CUR_ERR"; fi
}

stdout_has() {
	TESTS_RUN=$((TESTS_RUN + 1))
	if printf '%s\n' "$CUR_OUT" | grep -Fq -- "$2"; then pass "$1"
	else fail "$1" "stdout missing: $2"; fi
}

stderr_has() {
	TESTS_RUN=$((TESTS_RUN + 1))
	if printf '%s\n' "$CUR_ERR" | grep -Fq -- "$2"; then pass "$1"
	else fail "$1" "stderr missing: $2"; fi
}

# golden_match NAME FIXTURE_MD EXPECTED_JSON — runs the REAL converter
# (real jq, real Oniguruma) over FIXTURE_MD and diffs its canonicalized
# output against the canonicalized EXPECTED_JSON.
golden_match() {
	name=$1
	fixture_md=$2
	expected_json=$3
	TESTS_RUN=$((TESTS_RUN + 1))
	actual=$(env -i HOME="$WORK/home" PATH="$TOOLBOX" TMPDIR="$WORK" sh "$CONVERTER" --file "$fixture_md" 2>"$WORK/golden_err" | jq -S -c .)
	expected=$(jq -S -c . "$expected_json")
	if [ "$actual" = "$expected" ]; then
		pass "$name"
	else
		fail "$name" "actual:   $actual
       expected: $expected
       stderr:   $(cat "$WORK/golden_err")"
	fi
}

# ADF_STRUCTURAL_VALIDATOR — a static jq program checking the Jira-400
# landmines directly against a document's SHAPE, independent of any single
# fixture's content: root version/type, no empty text nodes, codeBlock text
# never carries marks, code never stacks with strong/em/strike, panelType
# is a valid enum value, heading level is 1-6, every link mark carries a
# non-empty href, the containers that must never be content:[] (tableRow,
# tableCell/tableHeader, bulletList/orderedList, listItem, blockquote,
# panel, table) all have at least one child, and blockquote/panel/table-
# cell children are always paragraphs (never raw text).
#
# Task lists (landmine #8) get five rules of their own, because a taskList
# is NOT shaped like a bulletList and a "fix" that makes it look like one is
# exactly the silent regression these catch: taskList/taskItem both carry a
# localId; a taskList's FIRST child must be a taskItem (ADF rejects a
# taskList that opens with a nested taskList); EVERY taskList child must be a
# taskItem or a taskList (a bulletList/orderedList there is a 400 — see the
# same-indent-escape regression in the task-list section below, which is the
# exact defect this rule exists to catch); a taskItem's state is the
# two-value enum TODO/DONE; and a taskItem's children are INLINE nodes
# directly — a paragraph wrapper there (the listItem shape) is itself a 400.
# An empty taskItem legitimately omits `content` entirely, so taskItem is
# deliberately NOT in needs_child.
#
# Prints a JSON array
# of violation strings — empty means valid. Optional REAL ADF-schema
# validation (e.g. a JSON Schema validator) is deliberately NOT wired in:
# no such validator is a guaranteed-present dependency for this suite (see
# the file header's "zero dependencies beyond jq" rationale) — this
# structural sweep is the guarded, always-available equivalent.
# shellcheck disable=SC2016  # single-quoted on purpose: this is a jq program, not a shell expansion
ADF_STRUCTURAL_VALIDATOR='
def needs_child: IN("tableRow","tableCell","tableHeader","bulletList","orderedList","listItem","blockquote","panel","table","taskList");
def is_inline_node: IN("text","hardBreak","emoji","mention","date","status","inlineCard","placeholder");
[
  (if .type != "doc" or .version != 1 then "root is not {type:\"doc\",version:1,...}" else empty end),
  (.. | objects | select(.type == "text" and ((.text // "") == "")) | "empty text node"),
  (.. | objects | select(.type == "codeBlock") | (.content // [])[] | select(has("marks")) | "codeBlock text node carries marks"),
  (.. | objects | select(has("marks")) | (.marks | map(.type)) as $mt
     | select(($mt | index("code")) != null and (($mt | index("strong")) != null or ($mt | index("em")) != null or ($mt | index("strike")) != null))
     | "code mark stacked with strong/em/strike"),
  (.. | objects | select(.type == "panel") | .attrs.panelType as $pt | select((["info","note","warning","success","error"] | index($pt)) == null) | "invalid panelType: \($pt)"),
  (.. | objects | select(.type == "heading") | .attrs.level as $lvl | select($lvl < 1 or $lvl > 6) | "invalid heading level: \($lvl)"),
  (.. | objects | select(has("marks")) | .marks[] | select(.type == "link") | select(((.attrs.href // "") | length) == 0) | "link mark missing href"),
  (.. | objects | select(.type | needs_child) | select(((.content // []) | length) == 0) | "\(.type) has empty/missing content"),
  (.. | objects | select(.type == "blockquote" or .type == "panel") | (.content // [])[] | select(.type != "paragraph") | "blockquote/panel child is not a paragraph"),
  (.. | objects | select(.type == "tableCell" or .type == "tableHeader") | (.content // [])[] | select(.type != "paragraph") | "table cell child is not a paragraph"),
  (.. | objects | select(.type == "taskList" or .type == "taskItem") | select(((.attrs.localId // "") | length) == 0) | "\(.type) missing attrs.localId"),
  (.. | objects | select(.type == "taskList") | select((((.content // [])[0]).type) != "taskItem") | "taskList first child is not a taskItem"),
  (.. | objects | select(.type == "taskList") | (.content // [])[] | select(.type != "taskItem" and .type != "taskList") | "taskList child is neither a taskItem nor a taskList: \(.type)"),
  (.. | objects | select(.type == "taskItem") | .attrs.state as $st | select((["TODO","DONE"] | index($st)) == null) | "invalid taskItem state: \($st)"),
  (.. | objects | select(.type == "taskItem") | (.content // [])[] | select((.type | is_inline_node) | not) | "taskItem child is not an inline node: \(.type)")
]
'

# assert_valid_adf NAME FIXTURE_MD — runs the real converter over
# FIXTURE_MD and asserts ADF_STRUCTURAL_VALIDATOR finds zero violations.
assert_valid_adf() {
	name=$1
	fixture_md=$2
	TESTS_RUN=$((TESTS_RUN + 1))
	actual=$(env -i HOME="$WORK/home" PATH="$TOOLBOX" TMPDIR="$WORK" sh "$CONVERTER" --file "$fixture_md" 2>"$WORK/valid_err")
	violations=$(printf '%s' "$actual" | jq -c "$ADF_STRUCTURAL_VALIDATOR")
	if [ "$violations" = "[]" ]; then
		pass "$name"
	else
		fail "$name" "violations: $violations"
	fi
}

# assert_invalid_adf NAME BAD_JSON — feeds a HAND-CRAFTED, KNOWN-INVALID
# ADF document (never run through the converter) directly into
# ADF_STRUCTURAL_VALIDATOR and asserts it reports at least one violation.
# the validator is trusted by every assert_valid_adf call and the
# blanket sweep — its REJECTION power was never itself tested (the
# index(.)-on-itself vacuous-bug class from an earlier round, where
# needs_child matched everything AND the inverse — a filter that always
# returns true rejects nothing just as silently as one that never fires —
# is exactly the failure mode this guards against). A validator that
# always says "valid" would pass every assert_valid_adf call and this
# section would be the only place that could ever catch it.
assert_invalid_adf() {
	name=$1
	bad_json=$2
	TESTS_RUN=$((TESTS_RUN + 1))
	violations=$(printf '%s' "$bad_json" | jq -c "$ADF_STRUCTURAL_VALIDATOR")
	if [ "$violations" != "[]" ]; then
		pass "$name"
	else
		fail "$name" "validator found NO violations in a document that is known-invalid: $bad_json"
	fi
}

# convert_md MD_TEXT — runs the REAL converter (real jq, real Oniguruma) over
# MD_TEXT and prints the resulting ADF document as compact JSON. The entry
# point for cases asserted by SHAPE (via assert_jq) rather than diffed against
# a golden file — see the task-list section for why some cases must not pin a
# golden.
#
# Deliberately returns 0 even when the converter dies: md-to-adf.sh carries
# runtime assertions that exit 1 rather than emit invalid ADF (see
# list_pop_and_fold), and every caller uses this inside `X=$(convert_md …)`,
# where a non-zero status would trip this file's own `set -e` and kill the run
# at that line — hiding every case after it behind a silent abort. Swallowing
# the status here leaves the output empty instead, so the caller's assertions
# report a NAMED failure. The status itself is not lost: a case that cares
# asserts it explicitly with the run/expect_rc pair above.
convert_md() {
	printf '%s\n' "$1" >"$WORK/case.md"
	env -i HOME="$WORK/home" PATH="$TOOLBOX" TMPDIR="$WORK" \
		sh "$CONVERTER" --file "$WORK/case.md" 2>"$WORK/case_err" || true
}

# assert_jq NAME DOC FILTER EXPECTED — applies FILTER to DOC with `jq -c` and
# asserts the compact-JSON result is exactly EXPECTED. Both the filter and the
# expected value stay at the call site (each case reads on its own); only the
# compare-and-report mechanics live here.
assert_jq() {
	aj_name=$1
	aj_doc=$2
	aj_filter=$3
	aj_expected=$4
	TESTS_RUN=$((TESTS_RUN + 1))
	aj_actual=$(printf '%s' "$aj_doc" | jq -c "$aj_filter")
	if [ "$aj_actual" = "$aj_expected" ]; then
		pass "$aj_name"
	else
		fail "$aj_name" "filter:   $aj_filter
       actual:   $aj_actual
       expected: $aj_expected"
	fi
}

