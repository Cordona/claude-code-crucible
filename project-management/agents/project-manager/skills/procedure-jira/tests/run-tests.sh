	pass "media: a mapped local image inside a code fence stays a codeBlock, never media"
else
	fail "media: a fenced mapped image stays a codeBlock" "mediaSingle=$fenced_media_count codeBlock=$fenced_code_count"
fi

# WITH the map but a MALFORMED UUID value: fail loud (a bad UUID would become
# an ADF value) — exit 1.
printf '%s' '![z](/local/z.png)' >"$WORK/media-baduuid.md"
printf '%s' '{"/local/z.png":"NOT-A-UUID"}' >"$WORK/media-baduuid-map.json"
