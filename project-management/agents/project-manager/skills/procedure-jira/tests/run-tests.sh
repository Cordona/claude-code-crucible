# Inline images (Cycle B): --media-map turns an own-line local `![alt](PATH)`
# into a mediaSingle block; every fallback preserves today's behavior.
# ===========================================================================
section "md-to-adf.sh — inline images: --media-map"

# convert_with_map NAME MD_TEXT MAP_JSON — writes MD_TEXT + MAP_JSON to temp
# files, runs the converter WITH --media-map, and leaves the canonicalized
# output document in $MEDIA_OUT for the caller to assert against.
MEDIA_OUT=""
convert_with_map() {
	cwm_md=$1
	cwm_map=$2
	printf '%s' "$cwm_md" >"$WORK/media.md"
	printf '%s' "$cwm_map" >"$WORK/media-map.json"
	MEDIA_OUT=$(env -i HOME="$WORK/home" PATH="$TOOLBOX" TMPDIR="$WORK" \
		sh "$CONVERTER" --file "$WORK/media.md" --media-map "$WORK/media-map.json" 2>"$WORK/media_err" | jq -S -c .)
}

MEDIA_MD='Intro paragraph.

![a diagram](/local/x.png)

Closing paragraph.'
MEDIA_UUID_FIX="aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee"
MEDIA_MAP_FIX="{\"/local/x.png\":\"$MEDIA_UUID_FIX\"}"

# WITH the map: the own-line local image is the EXACT verified mediaSingle
# block (collection:""), sitting as its own BLOCK between the two paragraphs.
convert_with_map "$MEDIA_MD" "$MEDIA_MAP_FIX"
TESTS_RUN=$((TESTS_RUN + 1))
media_block_types=$(printf '%s' "$MEDIA_OUT" | jq -c '[.content[].type]')
if [ "$media_block_types" = '["paragraph","mediaSingle","paragraph"]' ]; then
	pass "media: an own-line local image becomes its own mediaSingle block between paragraphs"
else
	fail "media: an own-line local image becomes its own mediaSingle block" "got: $media_block_types"
fi

TESTS_RUN=$((TESTS_RUN + 1))
media_block=$(printf '%s' "$MEDIA_OUT" | jq -S -c '.content[1]')
media_expected=$(printf '%s' "{\"type\":\"mediaSingle\",\"attrs\":{\"layout\":\"center\"},\"content\":[{\"type\":\"media\",\"attrs\":{\"type\":\"file\",\"id\":\"$MEDIA_UUID_FIX\",\"collection\":\"\"}}]}" | jq -S -c .)
if [ "$media_block" = "$media_expected" ]; then
	pass "media: the emitted block is EXACTLY the verified mediaSingle/media shape (collection is the empty string)"
else
	fail "media: the emitted block is EXACTLY the verified shape" "actual:   $media_block
       expected: $media_expected"
fi

# The mediaSingle document is still structurally valid ADF.
printf '%s' "$MEDIA_MD" >"$WORK/media-valid.md"
printf '%s' "$MEDIA_MAP_FIX" >"$WORK/media-valid-map.json"
TESTS_RUN=$((TESTS_RUN + 1))
media_valid_out=$(env -i HOME="$WORK/home" PATH="$TOOLBOX" TMPDIR="$WORK" \
	sh "$CONVERTER" --file "$WORK/media-valid.md" --media-map "$WORK/media-valid-map.json")
media_violations=$(printf '%s' "$media_valid_out" | jq -c "$ADF_STRUCTURAL_VALIDATOR")
if [ "$media_violations" = "[]" ]; then
	pass "media: the mediaSingle document passes the ADF structural sweep"
else
	fail "media: the mediaSingle document passes the ADF structural sweep" "violations: $media_violations"
fi

# WITHOUT the map: fallback — the image line degrades to paragraph text (the
# `!` stays literal, the local href drops per the scheme allow-list). NO
# mediaSingle node; the 139 baseline behavior is untouched.
TESTS_RUN=$((TESTS_RUN + 1))
printf '%s' "$MEDIA_MD" >"$WORK/media-nomap.md"
nomap_media_count=$(env -i HOME="$WORK/home" PATH="$TOOLBOX" TMPDIR="$WORK" \
	sh "$CONVERTER" --file "$WORK/media-nomap.md" | jq -c '[.content[] | select(.type=="mediaSingle")] | length')
if [ "$nomap_media_count" = "0" ]; then
	pass "media: WITHOUT --media-map, the image line degrades to text (no mediaSingle) — baseline behavior"
else
	fail "media: WITHOUT --media-map, the image line degrades to text" "got mediaSingle count: $nomap_media_count"
fi

# WITH the map but an http(s) target: fallback — an external URL is never a
# media block; it keeps today's link/text behavior (no mediaSingle).
convert_with_map '![x](https://example.com/x.png)' "$MEDIA_MAP_FIX"
TESTS_RUN=$((TESTS_RUN + 1))
http_media_count=$(printf '%s' "$MEDIA_OUT" | jq -c '[.content[] | select(.type=="mediaSingle")] | length')
if [ "$http_media_count" = "0" ]; then
	pass "media: an http(s) image is NOT a media block even with a map (fallback preserved)"
else
	fail "media: an http(s) image is NOT a media block even with a map" "got mediaSingle count: $http_media_count"
fi

# WITH the map but the local path is NOT a key: documented pass-through as
# text (never a crash, never a dropped line).
convert_with_map '![y](/local/not-in-map.png)' "$MEDIA_MAP_FIX"
TESTS_RUN=$((TESTS_RUN + 1))
unmapped_media_count=$(printf '%s' "$MEDIA_OUT" | jq -c '[.content[] | select(.type=="mediaSingle")] | length')
unmapped_para_count=$(printf '%s' "$MEDIA_OUT" | jq -c '[.content[] | select(.type=="paragraph")] | length')
if [ "$unmapped_media_count" = "0" ] && [ "$unmapped_para_count" -ge 1 ]; then
	pass "media: a local path NOT in the map passes through as paragraph text (documented fallback, no drop)"
else
	fail "media: a local path NOT in the map passes through as text" "mediaSingle=$unmapped_media_count paragraph=$unmapped_para_count"
fi

# WITH the map and a mapped local path, but NOT on its own line (image is
# mid-text): only a SOLELY-image line becomes media, so this stays paragraph
# text — the own-line boundary, proven in the negative direction. Matches
# jira.sh's scan_inline_image_paths (which likewise ignores a mid-text image).
convert_with_map 'see ![a diagram](/local/x.png) here' "$MEDIA_MAP_FIX"
TESTS_RUN=$((TESTS_RUN + 1))
midtext_media_count=$(printf '%s' "$MEDIA_OUT" | jq -c '[.content[] | select(.type=="mediaSingle")] | length')
midtext_para_count=$(printf '%s' "$MEDIA_OUT" | jq -c '[.content[] | select(.type=="paragraph")] | length')
if [ "$midtext_media_count" = "0" ] && [ "$midtext_para_count" -ge 1 ]; then
	pass "media: a mapped local image NOT on its own line (mid-text) stays paragraph text (only solely-image lines become media)"
else
	fail "media: a mid-text mapped image stays paragraph text" "mediaSingle=$midtext_media_count paragraph=$midtext_para_count"
fi

# WITH the map but the mapped image sits inside a ``` code fence: fence content
# is literal, so it is a codeBlock, never media — even with a matching map
