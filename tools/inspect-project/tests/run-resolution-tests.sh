#!/usr/bin/env sh
#
# run-resolution-tests.sh — how lib/intellij.sh finds the real IntelliJ binary:
#                           --idea-bin > $IDEA_BIN > a Toolbox launcher on PATH >
#                           a macOS app bundle > a clear "everything I tried"
#                           failure.
#
# WHAT EACH TEST OBSERVES. Resolution has exactly one observable channel — the
# `IntelliJ binary: <path>` line the script writes to stderr before running — plus
# the resolution log on failure. Every assertion here reads one of those two, never
# an internal variable, so a test cannot pass by agreeing with the implementation
# about a name.
#
# WHY $HOME IS THE FIXTURE. Two of the five strategies search the filesystem:
# `$HOME/Applications/IntelliJ IDEA*.app/...` and `/Applications/IntelliJ
# IDEA*.app/...`. Under lib/harness.sh's `env -i` isolation, $HOME is a temp
# directory, so the first is fully controllable — app bundles are built and torn
# down per test. `/Applications` is NOT controllable from a test: it is a real
# machine path this suite must not touch. See ENVIRONMENT ASSUMPTION below.
#
# ENVIRONMENT ASSUMPTION, stated rather than hidden: the "autodetection exhausted"
# test needs NO `/Applications/IntelliJ IDEA*.app/Contents/MacOS/idea` to exist on
# the host, because nothing in a test can hide one. JetBrains Toolbox installs to
# `~/Applications` by default, so this holds on an ordinary developer machine; the
# preflight below says so out loud if it does not, rather than letting the failure
# look like a regression in the tool.
#
# Usage:  sh run-resolution-tests.sh
#         VERBOSE=1 sh run-resolution-tests.sh
# Exit 0 = all passed, 1 = one or more failed.
#
set -eu

TESTS_DIR=$(cd "$(dirname "$0")" && pwd)
# shellcheck source=SCRIPTDIR/lib/harness.sh
. "$TESTS_DIR/lib/harness.sh"
# shellcheck source=SCRIPTDIR/lib/stubs.sh
. "$TESTS_DIR/lib/stubs.sh"
# shellcheck source=SCRIPTDIR/lib/rig.sh
. "$TESTS_DIR/lib/rig.sh"

rig_setup "$TESTS_DIR" resolution

SHIM_DIR="$WORK/bin-shim"
APPS="$HARNESS_HOME/Applications"
mkdir -p "$SHIM_DIR"

# run SELECTOR COMMAND... — the per-suite PATH map. The whole suite is about which
# of `idea`/a launcher/an app bundle exists, so these three compositions ARE the
# test matrix. $BIN_UNAME is on every one, because is_macos() selects between the
# two launcher strategies and only the stub can reach the other branch.
run() {
	r_selector=$1; shift
	case "$r_selector" in
		noidea)   r_path="$BIN_UNAME:$BIN_DATE:$TOOLBOX" ;;
		withidea) r_path="$BIN_IDEA:$BIN_UNAME:$BIN_DATE:$TOOLBOX" ;;
		shim)     r_path="$SHIM_DIR:$BIN_UNAME:$BIN_DATE:$TOOLBOX" ;;
		*) printf 'FATAL: bad run() selector: %s\n' "$r_selector" >&2; exit 1 ;;
	esac
	harness_run "$r_path" "$@"
}

# inspect SELECTOR RESULTS_TAG [FLAGS...] — the constant part of every invocation
# in this suite. `--scope all` keeps git out of it entirely.
inspect() {
	i_selector=$1
	i_results=$(results_root "$2")
	shift 2
	rig_reset_logs
	run "$i_selector" "$INSPECT" \
		--project "$PROJECT" --scope all --engine intellij \
		--output-root "$i_results" "$@"
}

# write_shim PATH TARGET — a JetBrains Toolbox launcher, in the shape that
# matters: a `#!` script whose body launches the real binary through macOS
# `open -na "<real path>"`. That quoted argument is the only thing
# intellij_extract_shim_target reads, and `open` DETACHING is why the launcher is
# used to DISCOVER the binary and never invoked to run the inspection.
write_shim() {
	cat >"$1" <<SHIM
#!/bin/sh
# Generated by JetBrains Toolbox (fixture)
open -na "$2" --args "\$@"
SHIM
	chmod +x "$1"
}

# app_bundle_binary NAME -> build \$HOME/Applications/<NAME>.app/Contents/MacOS/idea
# as a working copy of the idea stub, and print its path.
app_bundle_binary() {
	ab_dir="$APPS/$1.app/Contents/MacOS"
	mkdir -p "$ab_dir"
	cp "$BIN_IDEA/idea" "$ab_dir/idea"
	chmod +x "$ab_dir/idea"
	printf '%s' "$ab_dir/idea"
}

PROJECT=$(new_project resolvable src/main.rs)
IDEA_STUB_EDIR_SRC="$FIXTURES/edir-basic"

# --- preflight --------------------------------------------------------------
for preflight_candidate in "/Applications/IntelliJ IDEA"*.app/Contents/MacOS/idea; do
	[ -x "$preflight_candidate" ] || continue
	printf 'PREFLIGHT WARNING: %s exists on this host.\n' "$preflight_candidate" >&2
	printf '  No test can hide it, so the "autodetection exhausted" case below will\n' >&2
	printf '  resolve it and fail. That is an environment mismatch, not a regression.\n' >&2
done

# ===========================================================================
section "--idea-bin wins over everything"
# ===========================================================================
inspect withidea flag-wins --idea-bin "$BIN_IDEA/idea"
expect_rc "--idea-bin: the run succeeds" 0
stderr_has "--idea-bin: the flag's binary is the one used" "IntelliJ binary: $BIN_IDEA/idea"

# The flag and the environment name DIFFERENT binaries, so exactly one of them can
# be reported — which is what makes this a precedence test rather than two
# independent ones passing side by side.
ENV_ONLY=$(app_bundle_binary "Env Only")
IDEA_BIN=$ENV_ONLY
inspect withidea flag-beats-env --idea-bin "$BIN_IDEA/idea"
expect_rc "--idea-bin over \$IDEA_BIN: the run succeeds" 0
stderr_has "--idea-bin over \$IDEA_BIN: the FLAG's binary is used" \
	"IntelliJ binary: $BIN_IDEA/idea"
stderr_not_has "--idea-bin over \$IDEA_BIN: the env var's binary is NOT used" \
	"IntelliJ binary: $ENV_ONLY"
IDEA_BIN=""
rm -rf "$APPS"

# ===========================================================================
section "an EXPLICIT signal that does not work is a hard failure, never a fall-through"
# ===========================================================================
# Both --idea-bin and $IDEA_BIN name a binary the caller believes in. Silently
# ignoring a stale one and autodetecting a different IDE would run the inspection
# against a profile the caller never chose — so these must NOT reach the
# "steps tried" list, and stderr_not_has is what proves they did not.
inspect withidea flag-missing --idea-bin "$WORK/nope/idea"
expect_rc "--idea-bin missing: exit 1" 1
stderr_has "--idea-bin missing: the flag's own value is named" \
	"--idea-bin is not an executable file: $WORK/nope/idea"
stderr_not_has "--idea-bin missing: no generic autodetection log buries the real reason" \
	"Steps tried:"

inspect withidea flag-not-executable --idea-bin "$PROJECT"
expect_rc "--idea-bin a directory: exit 1" 1
stderr_has "--idea-bin a directory: rejected as not an executable FILE" \
	"--idea-bin is not an executable file: $PROJECT"

IDEA_BIN="$WORK/nope/idea"
inspect withidea env-missing
expect_rc "\$IDEA_BIN missing: exit 1" 1
stderr_has "\$IDEA_BIN missing: the variable's own value is named" \
	"\$IDEA_BIN is set but is not an executable file: $WORK/nope/idea"
stderr_has "\$IDEA_BIN missing: the remedy is named" "unset it, or point it at the real IntelliJ binary"
stderr_not_has "\$IDEA_BIN missing: no generic autodetection log" "Steps tried:"
IDEA_BIN=""

# ===========================================================================
section "\$IDEA_BIN wins over autodetection"
# ===========================================================================
# An `idea` launcher IS on PATH here and names a different binary, so the only way
# this can report the environment's is by preferring it.
ENV_BIN=$(app_bundle_binary "Env Wins")
write_shim "$SHIM_DIR/idea" "$BIN_IDEA/idea"
IDEA_BIN=$ENV_BIN
inspect shim env-beats-path
expect_rc "\$IDEA_BIN over PATH: the run succeeds" 0
stderr_has "\$IDEA_BIN over PATH: the environment's binary is used" "IntelliJ binary: $ENV_BIN"
stderr_not_has "\$IDEA_BIN over PATH: the launcher's target is NOT used" \
	"IntelliJ binary: $BIN_IDEA/idea"
IDEA_BIN=""
rm -rf "$APPS"

# ===========================================================================
section "a Toolbox launcher on PATH is a way to DISCOVER the binary, never to run it"
# ===========================================================================
write_shim "$SHIM_DIR/idea" "$BIN_IDEA/idea"
inspect shim shim-target
expect_rc "launcher: the run succeeds" 0
stderr_has "launcher: the \`open -na\` target is resolved as the real binary" \
	"IntelliJ binary: $BIN_IDEA/idea"
equals "launcher: the inspection ran in the project, i.e. the target really was invoked" \
	"$(sed -n '1p' "$IDEA_STUB_ARGV_LOG")" "CWD=$(cd "$PROJECT" && pwd)"

# --- a launcher naming a target that is not there ---------------------------
write_shim "$SHIM_DIR/idea" "$WORK/nope/idea"
inspect shim shim-dead-target
expect_rc "launcher with a dead target: exit 1" 1
stderr_has "launcher with a dead target: the recovered path is quoted back" \
	"points at \"$WORK/nope/idea\", which is not an executable file"
stderr_has "launcher with a dead target: autodetection is reported as exhausted" \
	"could not resolve the IntelliJ binary. Steps tried:"
stderr_has "launcher with a dead target: the remedy is named" "pass --idea-bin /path/to/idea explicitly"

# --- a launcher that is not a Toolbox launcher, on macOS -------------------
# On macOS there is nothing usable here: a launcher cannot be invoked directly
# because `open` detaches, and without a recoverable target there is no binary.
# The fixture is a WORKING CLI (a copy of the idea stub, which carries no
# `open -na` line), so a refusal here can only come from the macOS rule itself and
# not from the fixture being unusable.
cp "$BIN_IDEA/idea" "$SHIM_DIR/idea"
UNAME_STUB_S=Darwin
inspect shim plain-launcher-macos
expect_rc "macOS non-Toolbox launcher: exit 1" 1
stderr_has "macOS non-Toolbox launcher: refused because \`open\` detaches" \
	"a macOS launcher cannot be invoked directly (it detaches via \`open\`)"

# --- the same launcher, off macOS ------------------------------------------
# Elsewhere the strategy is ATTEMPTED but unverified, so a launcher with no
# recoverable target falls back to being treated as the real binary — and since
# this fixture really is a working CLI, the whole run completes.
UNAME_STUB_S=Linux
inspect shim plain-launcher-linux
expect_rc "non-macOS non-Toolbox launcher: the run succeeds" 0
stderr_has "non-macOS non-Toolbox launcher: it is used as the real binary" \
	"IntelliJ binary: $SHIM_DIR/idea"

# --- the shebang guard ----------------------------------------------------
# intellij_extract_shim_target checks for a `#!` FIRST, so a genuine compiled
# binary on PATH is never scanned byte-by-byte by sed. This fixture is not a
# script yet does contain an `open -na "..."` line: the guard must win, so the FILE
# becomes the binary rather than the string inside it.
#
# It is deliberately NOT a working CLI — a non-`#!` file that still executes would
# depend on the shell's ENOEXEC-retry behaviour, which varies. So the run fails at
# the INSPECTION stage, and the two stderr_not_has/stderr_has pairs below are what
# separate "resolution chose the file" from "resolution failed".
{
	printf '\177ELF not-a-script\n'
	printf 'open -na "%s" --args\n' "$WORK/nope/idea"
} >"$SHIM_DIR/idea"
chmod +x "$SHIM_DIR/idea"
inspect shim non-script-with-open-line
stderr_has "non-script launcher: the FILE is used, not the path quoted inside it" \
	"IntelliJ binary: $SHIM_DIR/idea"
stderr_not_has "non-script launcher: the embedded path is never even considered" \
	"$WORK/nope/idea"
stderr_not_has "non-script launcher: resolution itself did NOT fail" \
	"could not resolve the IntelliJ binary"
expect_rc "non-script launcher: the run then fails at the inspection, not at resolution" 1
stderr_has "non-script launcher: and says so" "wrote no report directory"
UNAME_STUB_S=Darwin
rm -f "$SHIM_DIR/idea"

# ===========================================================================
section "the macOS app-bundle fallback"
# ===========================================================================
BUNDLE_BIN=$(app_bundle_binary "IntelliJ IDEA Ultimate")
inspect noidea app-bundle
expect_rc "app bundle: the run succeeds" 0
stderr_has "app bundle: ~/Applications is searched when nothing else names a binary" \
	"IntelliJ binary: $BUNDLE_BIN"

# A non-executable candidate sorts FIRST under the glob, so the loop must skip it
# rather than resolve it — which is exactly what idea_bin_is_usable is for, and
# also what lets an unmatched glob be left literal without special-casing.
mkdir -p "$APPS/IntelliJ IDEA Broken.app/Contents/MacOS"
: >"$APPS/IntelliJ IDEA Broken.app/Contents/MacOS/idea"
inspect noidea app-bundle-skips-unusable
expect_rc "app bundle: an unusable earlier candidate is skipped, not resolved" 0
stderr_has "app bundle: the executable candidate is the one used" "IntelliJ binary: $BUNDLE_BIN"
rm -rf "$APPS"

# ===========================================================================
section "autodetection exhausted — every step tried, then the remedy"
# ===========================================================================
inspect noidea exhausted
expect_rc "exhausted: exit 1" 1
stderr_has "exhausted: reported as a resolution failure" \
	"could not resolve the IntelliJ binary. Steps tried:"
stderr_has "exhausted: step 1 — the flag" "--idea-bin was not given"
stderr_has "exhausted: step 2 — the environment" "\$IDEA_BIN was not set"
stderr_has "exhausted: step 3 — PATH" "\`idea\` is not on PATH"
stderr_has "exhausted: step 4 — the app bundles, both roots named" \
	"under /Applications or $HARNESS_HOME/Applications"
stderr_has "exhausted: the remedy names the macOS path shape" \
	"inside 'IntelliJ IDEA.app/Contents/MacOS/idea'"
stderr_has "exhausted: the remedy names the Windows route" \
	"on Windows use Git Bash or WSL and point it at idea.bat"
path_absent "exhausted: no empty run directory is left behind" \
	"$(run_dir_of "$WORK/results/exhausted" resolvable)"

summarize
